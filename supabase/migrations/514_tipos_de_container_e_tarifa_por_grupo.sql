-- 514: Tipos de container e tarifas por grupo (lote 0B do plano da
-- repaginação da Demurrage; ADR 0112, D28 a D34).
--
-- Antes, o grupo de tarifa vinha de uma lista fixa de 26 códigos no banco
-- (`_demurrage_canonical_type`, 138) e no navegador; os tipos dos B/Ls fora da
-- lista (48FR, 40FM, 40FP…) nunca achavam tarifa e nunca entravam em atraso. A
-- tela de tarifas mostrava 12 linhas, mas o cálculo usava uma por grupo.
--
-- Agora:
-- 1. `demurrage_rate_groups`: os seis grupos de tarifa (20' dry, 40' dry, 20'
--    especial, 40' especial, 20' reefer, 40' reefer), pelo código de hoje
--    (20GP, 40GP, 20FR, 40FR, 20RF, 40RF).
-- 2. `container_types`: cadastro **Tipos de container** (código como vem no
--    B/L, descrição, grupo e situação). Qualquer usuário ativo inclui e edita;
--    desativar, reativar e excluir são do Administrativo (D34, como as
--    tarifas). Carga inicial: os 13 códigos dos B/Ls (D30) e os códigos da
--    lista antiga, no mesmo grupo de antes.
-- 3. `_demurrage_canonical_type` lê o cadastro: tipo inativo ou fora dele não
--    tem grupo (NULL) e, portanto, não tem tarifa.
-- 4. `demurrage_rates.container_type` passa a guardar o grupo (FK), uma linha
--    por grupo (D28): o banco recusa duas tarifas ativas no mesmo grupo com
--    vigência sobreposta, como nos acordos.
-- 5. O Portal mostra o nome do grupo e os códigos que ele cobre.
--
-- Dados: depende da linha "Data status" do AGENTS.md (2026-09-18), porque
-- reescreve `demurrage_rates`: cada tarifa passa a apontar para o grupo, e as
-- linhas repetidas de um grupo saem, ficando a que o cálculo usava
-- (`_active_demurrage_rates`: vigência mais recente, depois o maior id). Nenhum
-- valor muda.
--
-- Rollback: recriar `_demurrage_canonical_type` e `_portal_information_core`
-- (138), `delete_catalog_row` (329) e `reactivate_catalog_row` (475); apagar a
-- restrição `demurrage_rates_one_per_group`, a FK
-- `demurrage_rates_container_type_group_fkey`, as tabelas `container_types` e
-- `demurrage_rate_groups`; as linhas apagadas de `demurrage_rates` voltam pela
-- carga inicial (seed).

