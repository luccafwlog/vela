-- Grupo do tipo pelo cadastro. Também aceita o próprio código do grupo, que é
-- o que a tarifa guarda.
-- ponytail: o código do grupo é um código de tipo (20GP, 40FR…); um container
-- desse código com o tipo desativado ainda acha o grupo pelo segundo ramo.
-- Upgrade: tarifa com chave de grupo própria, separada dos códigos de tipo.
CREATE OR REPLACE FUNCTION public._demurrage_canonical_type(p_type text)
 RETURNS text
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT COALESCE(
    (SELECT t.rate_group FROM public.container_types t WHERE t.code = upper(btrim(COALESCE(p_type, ''))) AND t.active),
    (SELECT g.code FROM public.demurrage_rate_groups g WHERE g.code = upper(btrim(COALESCE(p_type, ''))))
  );
$function$;
REVOKE ALL ON FUNCTION public._demurrage_canonical_type(text) FROM PUBLIC, anon, authenticated;

-- Uma tarifa por grupo (D28). As linhas repetidas saem; fica a que
-- `_active_demurrage_rates` escolhia (vigência mais recente, depois maior id).
-- Tarifa vigente conta como usada (091): a marca de catálogo libera a troca.
SET vela.seed_catalog = 'on';
DO $one_per_group$
DECLARE
  v_unknown text;
BEGIN
  SELECT string_agg(DISTINCT r.container_type, ', ') INTO v_unknown
    FROM public.demurrage_rates r
   WHERE public._demurrage_canonical_type(r.container_type) IS NULL;
  IF v_unknown IS NOT NULL THEN
    RAISE EXCEPTION 'Tarifa de Demurrage com tipo fora dos grupos: %.', v_unknown;
  END IF;
END;
$one_per_group$;

DELETE FROM public.demurrage_rates r
 WHERE r.active
   AND EXISTS (
     SELECT 1 FROM public.demurrage_rates other
      WHERE other.active
        AND other.id <> r.id
        AND public._demurrage_canonical_type(other.container_type) = public._demurrage_canonical_type(r.container_type)
        AND daterange(other.valid_from, other.valid_to, '[]') && daterange(r.valid_from, r.valid_to, '[]')
        AND (other.valid_from, other.id) > (r.valid_from, r.id)
   );

UPDATE public.demurrage_rates
   SET container_type = public._demurrage_canonical_type(container_type)
 WHERE container_type IS DISTINCT FROM public._demurrage_canonical_type(container_type);
RESET vela.seed_catalog;

ALTER TABLE public.demurrage_rates
  ADD CONSTRAINT demurrage_rates_container_type_group_fkey
  FOREIGN KEY (container_type) REFERENCES public.demurrage_rate_groups(code);
ALTER TABLE public.demurrage_rates
  ADD CONSTRAINT demurrage_rates_one_per_group
  EXCLUDE USING gist (container_type WITH =, daterange(valid_from, valid_to, '[]') WITH &&) WHERE (active);

CREATE OR REPLACE FUNCTION public.delete_catalog_row(p_table text, p_id text, p_reason text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_count integer;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_active_user() THEN
    RAISE EXCEPTION 'Somente o Administrativo pode excluir.' USING ERRCODE = '42501';
  END IF;
  -- Linha de serviço de vazios é custo interno: qualquer usuário ativo exclui
  -- (ADR 0071, política da migration 087). O resto é do Administrativo.
  IF p_table <> 'vazios_export_service_lines' AND NOT public.is_admin() THEN
    RAISE EXCEPTION 'Somente o Administrativo pode excluir.' USING ERRCODE = '42501';
  END IF;
  IF p_table NOT IN (
    'depots', 'depot_services', 'vazios_export_service_lines',
    'demurrage_rates', 'customer_demurrage_agreements', 'customer_rate_overrides',
    'charge_table_items', 'container_types'
  ) THEN
    RAISE EXCEPTION 'Tabela fora da exclusão de cadastro: %.', p_table USING ERRCODE = '22023';
  END IF;
  IF NULLIF(btrim(p_reason), '') IS NULL THEN
    RAISE EXCEPTION 'Informe o motivo da exclusão.' USING ERRCODE = '22023';
  END IF;

  -- B14 (ADR 0071, item 4): linha de serviço de vazios trava com o ADR de
  -- Saída fechado da escala; reabrir o ADR solta a trava.
  IF p_table = 'vazios_export_service_lines' AND EXISTS (
    SELECT 1 FROM public.vazios_export_service_lines AS line
    JOIN public.vazios_export_operations AS op ON op.id = line.operation_id
    WHERE line.id::text = p_id AND public._vazios_export_locked_by_adr(op.voyage_id, op.embark_port)
  ) THEN
    RAISE EXCEPTION 'ADR de Saida fechado: reabra o ADR para excluir a linha de servico de vazios.' USING ERRCODE = '23514';
  END IF;

  PERFORM set_config('vela.delete_reason', btrim(p_reason), true);
  -- ponytail: id::text evita um ramo por tipo de chave (uuid/bigint); perde o
  -- índice, aceitável em cadastros pequenos. Se uma tabela crescer, comparar
  -- no tipo da coluna.
  EXECUTE format('DELETE FROM public.%I WHERE id::text = $1', p_table) USING p_id;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  PERFORM set_config('vela.delete_reason', '', true);

  IF v_count = 0 THEN
    RAISE EXCEPTION 'Nada foi excluído: o registro já não existe.' USING ERRCODE = 'P0002';
  END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.reactivate_catalog_row(p_table text, p_id text, p_reason text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_reason text := NULLIF(btrim(COALESCE(p_reason, '')), '');
  v_count integer;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_active_user() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Somente o Administrativo reativa.' USING ERRCODE = '42501';
  END IF;
  IF p_table NOT IN (
    'charge_tables', 'charge_table_items', 'customer_rate_overrides',
    'demurrage_rates', 'customer_demurrage_agreements', 'user_profiles',
    'depots', 'depot_services', 'container_types'
  ) THEN
    RAISE EXCEPTION 'Tabela fora da reativação de cadastro: %.', p_table USING ERRCODE = '22023';
  END IF;
  IF v_reason IS NULL THEN
    RAISE EXCEPTION 'Informe o motivo da reativação.' USING ERRCODE = '22023';
  END IF;

  PERFORM set_config('vela.import_context', 'Reativação: ' || v_reason, true);
  -- 475 (ACE-D12): no usuário, o motivo vai na linha da troca de situação que o
  -- gatilho `audit_user_profile_changes` grava (assunto Usuário, com o nome),
  -- e não sai a segunda linha genérica.
  IF p_table = 'user_profiles' THEN
    PERFORM set_config('vela.access_change_reason', v_reason, true);
  END IF;
  -- ponytail: id::text evita um ramo por tipo de chave (uuid/bigint), como em
  -- delete_catalog_row; cadastros pequenos.
  EXECUTE format('UPDATE public.%I SET active = true WHERE id::text = $1 AND active = false', p_table) USING p_id;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  PERFORM set_config('vela.import_context', '', true);
  PERFORM set_config('vela.access_change_reason', '', true);

  IF v_count = 0 THEN
    RAISE EXCEPTION 'Nada foi reativado: o registro não existe ou já está ativo.' USING ERRCODE = 'P0002';
  END IF;

  IF p_table <> 'user_profiles' THEN
    INSERT INTO public.audit_logs (entity_type, entity_id, field_name, old_value, new_value, changed_by, justification)
    VALUES (p_table, p_id, 'reativado', 'false', 'true', auth.uid(), v_reason);
  END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public._portal_information_core(p_internal boolean DEFAULT false) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO public, pg_temp AS $$
SELECT jsonb_build_object(
  'depots', COALESCE((SELECT jsonb_agg(jsonb_build_object(
    'id', d.id, 'code', d.code, 'name', COALESCE(d.name,d.code), 'active', d.active,
    'ports', COALESCE(i.ports,'{}'::text[]), 'address', COALESCE(i.address,''),
    'opening_hours', COALESCE(i.opening_hours,''), 'emails', COALESCE(i.emails,'{}'::text[]),
    'phones', COALESCE(i.phones,'{}'::text[]), 'scheduling_url', i.scheduling_url,
    'instructions', COALESCE(i.instructions,''), 'restrictions', COALESCE(i.restrictions,''),
    'published', COALESCE(i.published,false), 'updated_at', i.updated_at
  ) ORDER BY d.code) FROM public.depots d LEFT JOIN public.depot_portal_information i ON i.depot_id=d.id
    WHERE d.tipo='depot' AND (p_internal OR (d.active AND i.published))), '[]'::jsonb),
  'agents', COALESCE((SELECT jsonb_agg(jsonb_build_object('id',a.id,'name',a.name,'ports',a.ports,'emails',a.emails,'active',a.active) ORDER BY a.name)
    FROM public.port_agents a WHERE p_internal OR a.active), '[]'::jsonb),
  'contacts', COALESCE((SELECT jsonb_agg(jsonb_build_object('key',c.key,'title',c.title,'description',c.description,'emails',c.emails,'phones',c.phones,'whatsapp',c.whatsapp,'address',c.address,'active',c.active) ORDER BY c.key)
    FROM public.portal_information_contacts c WHERE p_internal OR c.active), '[]'::jsonb),
  'carriers', COALESCE((SELECT jsonb_agg(jsonb_build_object('carrier_id',c.id,'name',c.name,'tracking_url',i.tracking_url) ORDER BY c.name)
    FROM public.carriers c LEFT JOIN public.carrier_portal_information i ON i.carrier_id=c.id WHERE p_internal OR i.tracking_url IS NOT NULL), '[]'::jsonb),
  'local_tables', COALESCE((SELECT jsonb_agg(jsonb_build_object('id',t.id,'name',t.name,'pod',public.normalize_port_code(t.pod),'cargo_mode',t.cargo_mode,'valid_from',t.valid_from,'valid_to',t.valid_to,
    'items',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',i.id,'name',i.name,'currency',COALESCE(i.currency,'BRL'),'unit_value_brl',i.unit_value_brl,'unit_value_usd',i.unit_value_usd,
       'application_basis',i.application_basis,'cargo_profile',i.cargo_profile,'manual_only',i.manual_only,'applies_to_soc',i.applies_to_soc) ORDER BY i.sort_order,i.id)
      FROM public.charge_table_items i WHERE i.charge_table_id=t.id AND i.active), '[]'::jsonb)) ORDER BY t.pod,t.cargo_mode)
    FROM public.charge_tables t WHERE t.active AND t.id=public.resolve_local_charge_table_id(t.cargo_mode,t.pod)), '[]'::jsonb),
  'demurrage_rates', COALESCE((SELECT jsonb_agg(jsonb_build_object('id',r.id,'container_type',r.container_type,
    'group_name',g.name,'codes',COALESCE((SELECT jsonb_agg(t.code ORDER BY t.code) FROM public.container_types t WHERE t.rate_group=g.code AND t.active),'[]'::jsonb),
    'free_days',r.free_days,'p1_day_from',r.p1_day_from,'p1_day_to',r.p1_day_to,
    'p1_usd',r.p1_usd,'p2_day_from',r.p2_day_from,'p2_usd',r.p2_usd,'valid_from',r.valid_from,'valid_to',r.valid_to) ORDER BY g.sort_order, r.container_type)
    FROM public._active_demurrage_rates((now() AT TIME ZONE 'America/Sao_Paulo')::date) r
    JOIN public.demurrage_rate_groups g ON g.code=r.container_type), '[]'::jsonb),
  'demurrage_notes', COALESCE((SELECT demurrage_notes FROM public.portal_information_settings WHERE id=1),''),
  'ports', COALESCE((SELECT jsonb_agg(jsonb_build_object('code',p.code,'name',p.name) ORDER BY p.name) FROM (
    SELECT DISTINCT ON (code) code,name FROM (
      SELECT public.normalize_port_code(locode) code,COALESCE(name,locode) name,0 priority FROM public.ports WHERE locode LIKE 'BR%'
      UNION ALL SELECT unnest(i.ports),unnest(i.ports),1 FROM public.depot_portal_information i JOIN public.depots d ON d.id=i.depot_id WHERE p_internal OR (d.active AND i.published)
      UNION ALL SELECT unnest(ports),unnest(ports),1 FROM public.port_agents WHERE p_internal OR active
    ) x WHERE code IS NOT NULL ORDER BY code,priority
  ) p), '[]'::jsonb)
);
$$;
